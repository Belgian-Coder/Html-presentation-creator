// The editor's previews and media settings: the preview of how one element appears (effect, speed, easing, repeat
// previews, nothing written into the slide), the preview of a slide transition (previous slide leaving, zoom, ends by
// itself / by click / by Esc), the text size keys and the undo History list (names, jump back, redo, keys, clicks),
// image Focus (object-position), logo settings (corner, size, large, show, hide on a slide, live stage), image Zoom.
export const covers = ['js/17-', 'js/18-', 'js/19-', 'js/20-', 'css/13-', 'css/03-', 'css/04-'];
export const timeoutMs = 180000;

export default async function (t) {
  const E = t.editor;
  const ev = t.eval;
  const gone = sel => `!document.querySelector(${JSON.stringify(sel)})`;
  const pressEsc = () => t.key('Escape', 'Escape', 27);
  await E.open('numbers');

  // ---------- 1. preview how one element appears ----------
  await E.pick('.editor-stage .scene h2'); await E.blur();
  await E.insert('rect');
  await E.panelSet('[data-element-field="--x"]', '300');
  await E.panelSet('[data-element-field="--y"]', '560');
  await E.panelSet('[data-element-field="--w"]', '200');
  await E.tab('element');
  const first = `document.querySelectorAll('.editor-stage .scene > .shape')[0]`;
  // the running preview, read in one go (a short preview may end between two reads on a busy machine)
  const anim = async () => {
    const found = await t.waitFor(`(() => { const e = ${first}; const list = e.getAnimations().map(a => { const k = a.effect.getKeyframes(); const prop = Object.keys(k[0]).find(n => !['offset', 'easing', 'composite', 'computedOffset'].includes(n)); return { prop, duration: Math.round(a.effect.getComputedTiming().duration), easing: a.effect.getTiming().easing, from: k[0][prop], to: k[k.length - 1][prop] }; }); return list.length ? { list, previewing: e.classList.contains('is-previewing') } : null; })()`, { label: 'a preview runs' });
    return { ...found, duration: Math.max(...found.list.map(a => a.duration)) };
  };

  await E.panelSet('[data-element-field="appear"]', 'slide');
  let a = await anim();
  t.check('choosing "with the slide" plays its rise-in at once', a.previewing && a.list.length === 1 && /translateY\(28px\)/.test(JSON.stringify(a.list)), JSON.stringify(a));
  await t.waitFor(`!${first}.classList.contains('is-previewing') && ${first}.getAnimations().length === 0`, { timeout: 8000, label: 'preview ends' });
  t.check('after the preview the element is still again (class removed)', true);
  await E.panelSet('[data-element-field="speed"]', '2s');
  a = await anim();
  t.check('Speed: the preview takes 2 s', a.duration === 2000, JSON.stringify(a));
  await E.panelSet('[data-element-field="appear"]', 'click');
  await E.panelSet('[data-element-field="effect"]', 'pop');
  a = await anim();
  t.check('pop: opacity and transform each with their own timing', a.list.some(x => x.prop === 'transform' && /^matrix\(0\.4/.test(x.from) && x.duration === 2000) && a.list.some(x => x.prop === 'opacity' && x.from === '0'), JSON.stringify(a));
  await E.panelSet('[data-element-field="effect"]', 'blur');
  a = await anim();
  t.check('blur: from blurred to sharp', a.list.some(x => x.prop === 'filter' && /blur\(14px\)/.test(x.from) && /^(none|blur\(0px\))$/.test(x.to)), JSON.stringify(a));
  await E.panelSet('[data-element-field="ease"]', 'var(--ease-elastic)');
  a = await anim();
  t.check('easing: the preview uses it', a.list.every(x => /^linear\(/.test(x.easing)), JSON.stringify(a));
  await t.click('.editor-panel-body [data-action="preview-appear"]');
  await t.click('.editor-panel-body [data-action="preview-appear"]');
  await t.waitFor(`${first}.classList.contains('is-previewing') && ${first}.getAnimations().length > 0 && getComputedStyle(${first}).filter !== 'none'`, { label: 'second preview shows' });
  t.check('a second preview right after the first still shows (stays previewing, moving)', true);
  await E.panelSet('[data-element-field="ease"]', '');
  await E.panelSet('[data-element-field="effect"]', 'strike');
  await t.waitFor(`parseFloat(getComputedStyle(${first}).backgroundSize) < 100 || /^0/.test(getComputedStyle(${first}).backgroundSize)`, { label: 'strike line draws' });
  t.check('strike: the line draws during the preview', true);
  await t.waitFor(`!${first}.classList.contains('is-previewing') && ${first}.getAnimations().length === 0`, { timeout: 8000, label: 'preview ends' });
  await t.click('.editor-panel-body [data-action="preview-appear"]');
  t.check('Preview plays it again', (await anim()).list.length > 0);
  await t.waitFor(`!${first}.classList.contains('is-previewing')`, { timeout: 8000, label: 'preview ends' });
  t.check('nothing is written into the slide by a preview', !/is-previewing/.test(await E.modelHtml()));

  // ---------- 2. preview a slide transition ----------
  await E.tab('slide');
  await t.click('.editor-panel-body [data-action="preview-transition"]');
  const state = () => ev(`(() => { const s = document.querySelector('.editor-transition-preview'); if (!s) return null; const scenes = [...s.querySelectorAll(':scope > .scene')]; const r = s.getBoundingClientRect(), c = document.querySelector('.editor-stage').getBoundingClientRect(); return { n: scenes.length, leaving: scenes[0].classList.contains('is-leaving'), active: scenes[scenes.length - 1].classList.contains('is-active'), names: scenes.map(x => x.dataset.name), sameBox: Math.abs(r.width - c.width) < 2 && Math.abs(r.left - c.left) < 2, opacityNew: getComputedStyle(scenes[scenes.length - 1]).opacity }; })()`);
  await t.waitFor(`!!document.querySelector('.editor-transition-preview')`, { label: 'transition preview' });
  const s1 = await state();
  t.check('Preview shows the slide before (leaving) and this slide (coming on) over the canvas', s1 && s1.n === 2 && s1.leaving && s1.active && s1.names[1] === 'numbers' && s1.sameBox, JSON.stringify(s1));
  t.check('the slide before shows its content while it leaves (not empty)', await ev(`[...document.querySelectorAll('.editor-transition-preview > .scene.is-leaving .reveal')].every(r => getComputedStyle(r).opacity === '1')`));
  t.check('the logo stays during the preview', await ev(`!!document.querySelector('.editor-transition-preview > .logo')`));
  const width0 = await ev(`document.querySelector('.editor-stage').getBoundingClientRect().width`);
  const matches = `(() => { const r = document.querySelector('.editor-transition-preview')?.getBoundingClientRect(), c = document.querySelector('.editor-stage').getBoundingClientRect(); return !!r && Math.abs(r.width - c.width) < 2; })()`;
  await t.key('=', 'Equal', 187, 2);
  await t.waitFor(`document.querySelector('.editor-stage').getBoundingClientRect().width !== ${width0} && ${matches}`, { label: 'zoom keeps preview on canvas' });
  t.check('zooming during the preview keeps it on the canvas', true);
  await t.key('0', 'Digit0', 48, 2);
  await t.waitFor(`Math.abs(document.querySelector('.editor-stage').getBoundingClientRect().width - ${width0}) < 2 && ${matches}`, { label: 'zoom reset' });
  await t.waitFor(`parseFloat(document.querySelector('.editor-transition-preview > .scene.is-active')?.style.opacity || getComputedStyle(document.querySelector('.editor-transition-preview > .scene.is-active')).opacity) > 0.3`, { label: 'new slide on its way in' });
  t.check('it plays: the new slide is on its way in', true);
  await t.waitFor(gone('.editor-transition-preview'), { timeout: 8000, label: 'preview ends by itself' });
  t.check('it ends by itself', true);
  await E.panelSet('[data-slide-field="transition"]', 'zoom');
  await t.waitFor(`document.querySelector('.editor-transition-preview')?.dataset.transition === 'zoom'`, { label: 'zoom preview' });
  t.check('changing the transition plays it at once (zoom)', true);
  const box = await ev(`(() => { const r = document.querySelector('.editor-transition-preview').getBoundingClientRect(); return { x: r.x + 50, y: r.y + 50 }; })()`);
  await t.clickAt(box);
  await t.waitFor(gone('.editor-transition-preview'), { label: 'click ends preview' });
  t.check('a click ends it', true);
  await t.click('.editor-panel-body [data-action="preview-transition"]');
  await t.waitFor(`!!document.querySelector('.editor-transition-preview')`);
  await pressEsc();
  await t.waitFor(gone('.editor-transition-preview'), { label: 'Esc ends preview' });
  t.check('Esc ends the preview (and keeps the editor open)', await ev(`!document.querySelector('.editor').hidden`));
  await E.goSlide('title');
  await E.tab('slide');
  await t.click('.editor-panel-body [data-action="preview-transition"]');
  await t.waitFor(`!!document.querySelector('.editor-transition-preview')`);
  t.check('the first slide: only it comes on', (await ev(`document.querySelectorAll('.editor-transition-preview > .scene').length`)) === 1);
  await E.undo();
  await t.waitFor(gone('.editor-transition-preview'), { label: 'undo ends preview' });
  t.check('nothing of the preview stays after a change or undo', !/editor-transition-preview/.test(await E.modelHtml()));

  // ---------- 3. text size keys and the History list ----------
  await E.goSlide('numbers');
  const h2 = `document.querySelector('.editor-stage .scene h2')`;
  const fontSize = () => ev(`(((${h2}).getAttribute('data-text-size') || '').split(' ')[0] || (${h2}).style.fontSize)`);   // (v183: the size as chosen)
  const sizeKey = async bigger => {
    const before = await fontSize();
    await t.send('Input.dispatchKeyEvent', { type: 'keyDown', key: bigger ? '>' : '<', code: bigger ? 'Period' : 'Comma', windowsVirtualKeyCode: bigger ? 190 : 188, modifiers: 10 });
    await t.send('Input.dispatchKeyEvent', { type: 'keyUp', key: bigger ? '>' : '<', code: bigger ? 'Period' : 'Comma', windowsVirtualKeyCode: bigger ? 190 : 188, modifiers: 10 });
    return before;
  };
  const sizeTo = async (bigger, expected) => { await sizeKey(bigger); await t.waitFor(`(((${h2}).getAttribute('data-text-size') || '').split(' ')[0] || (${h2}).style.fontSize) === ${JSON.stringify(expected)}`, { label: 'size ' + expected }); };
  await E.pick('.editor-stage .scene h2'); await E.blur();
  await sizeTo(true, '110%');
  t.check('Ctrl+Shift+> : one size bigger (110%)', true);
  await sizeTo(true, '125%'); await sizeTo(true, '150%');
  t.check('again: 125%, then 150%', true);
  await sizeTo(false, '125%'); await sizeTo(false, '110%'); await sizeTo(false, '');
  t.check('Ctrl+Shift+< back to normal (no size written)', !/font-size/.test(await ev(`${h2}.getAttribute('style') || ''`)));
  await sizeTo(false, '90%'); await sizeKey(false); await sizeKey(false); await t.waitFor(`(((${h2}).getAttribute('data-text-size') || '').split(' ')[0] || (${h2}).style.fontSize) === '75%'`, { label: 'size 75%' });
  t.check('smaller than normal: 90%, down to 75%', true);
  const historyCount = async () => {
    await t.click('.editor-bar [data-action="history"]');
    await t.waitFor(`!!document.querySelector('.editor-history')`);
    const n = await ev(`document.querySelectorAll('.editor-history button').length`);
    await pressEsc();
    await t.waitFor(gone('.editor-history'));
    return n;
  };
  const c0 = await historyCount();
  await sizeKey(false);
  await t.settle();
  const c1 = await historyCount();
  t.check('at the smallest size the key adds no empty step', (await fontSize()) === '75%' && c1 === c0, JSON.stringify([c0, c1]));
  await sizeKey(true); await sizeKey(true);
  await t.waitFor(`${h2}.style.fontSize !== '75%'`);
  await E.tab('element');
  await E.panelSet('[data-tool-field="color"]', 'var(--color-accent)');
  await t.waitFor(`${h2}.style.color === 'var(--color-accent)'`);
  const shapes = () => ev(`document.querySelectorAll('.editor-stage .scene > .shape').length`);
  const shapes0 = await shapes();
  await E.insert('rect');
  await t.click('.editor-bar [data-action="history"]');
  await t.waitFor(`!!document.querySelector('.editor-history')`);
  const names = () => ev(`[...document.querySelectorAll('.editor-history button')].map(b => b.querySelector('span').textContent)`);
  const items = await names();
  t.check('History lists the changes by name, newest first', items.length >= 7 && items[1] === 'Colour' && items.slice(2, 9).includes('Text bigger') && items.slice(2, 9).includes('Text smaller'), JSON.stringify(items));
  await ev(`document.querySelectorAll('.editor-history button')[1].click()`);
  await t.waitFor(`${h2}.style.color === '' && document.querySelectorAll('.editor-stage .scene > .shape').length === ${shapes0}`, { label: 'went back two steps' });
  t.check('a click goes back to just before that change (two steps here)', true);
  t.check('the list closes', await ev(gone('.editor-history')));
  await E.blur();
  await t.key('y', 'KeyY', 89, 2);
  await t.waitFor(`${h2}.style.color === 'var(--color-accent)'`);
  await t.key('y', 'KeyY', 89, 2);
  await t.waitFor(`document.querySelectorAll('.editor-stage .scene > .shape').length === ${shapes0 + 1}`);
  t.check('Redo brings both back', true);
  await t.click('.editor-bar [data-action="history"]');
  await t.waitFor(`!!document.querySelector('.editor-history')`);
  t.check('after redo the names are kept', (await names())[1] === 'Colour');
  await pressEsc();
  await t.waitFor(gone('.editor-history'));
  t.check('Esc closes the list (the editor stays)', await ev(`!document.querySelector('.editor').hidden`));
  const hb = await t.centre('.editor-bar [data-action="history"]');
  await t.clickAt(hb);
  await t.waitFor(`!!document.querySelector('.editor-history')`);
  const steps0 = await ev(`document.querySelectorAll('.editor-history button').length`);
  const x0 = await ev(`document.querySelector('.editor-stage .scene > .shape')?.style.getPropertyValue('--x') || ''`);
  await t.key('ArrowDown', 'ArrowDown', 40);
  await t.waitFor(`document.activeElement.closest('.editor-history') !== null`, { label: 'focus in list' });
  t.check('arrows move through the list, not the selected element', (await ev(`document.querySelector('.editor-stage .scene > .shape')?.style.getPropertyValue('--x') || ''`)) === x0);
  await t.clickAt(hb);
  await t.waitFor(gone('.editor-history'), { label: 'second click closes' });
  t.check('History opens with a click and a second click closes', steps0 > 0);
  await t.click('.editor-slides [data-action="add-slide"]');
  await t.waitFor(`!!document.querySelector('.editor-template-grid [data-action="add-template"]')`);
  await ev(`document.querySelector('.editor-template-grid [data-action="add-template"]').click()`);
  await t.waitFor(`document.querySelectorAll('.editor-slide-list > li').length > 1 && !document.querySelector('.editor-template-grid')`).catch(() => {});
  await t.click('.editor-bar [data-action="history"]');
  await t.waitFor(`!!document.querySelector('.editor-history')`);
  const name = await ev(`document.querySelector('.editor-history button span').textContent`);
  t.check('adding a slide has a short clean name', /^[^\n]{1,48}$/.test(name), name);
  await pressEsc();
  await t.waitFor(gone('.editor-history'));

  // ---------- 4. image Focus ----------
  await E.goSlide('numbers');
  await E.pick('.editor-stage .scene h2'); await E.blur();
  await E.insert('image');
  await E.tab('element');
  const img = `document.querySelector('.editor-stage .is-editor-selected img, .editor-stage img.is-editor-selected')`;
  const field = name => `document.querySelector('.editor-panel-body [data-tool-field="${name}"]')`;
  t.check('an image has a Focus field', await ev(`!!${field('objectPosition')}`));
  await E.panelSet('[data-tool-field="objectFit"]', 'cover');
  await E.panelSet('[data-tool-field="objectPosition"]', '50% 0%');
  await t.waitFor(`${img}.style.objectPosition === '50% 0%'`);
  t.check('Focus Top: object-position 50% 0% (plain CSS on the image)', /object-position: 50% 0%/.test(await E.modelHtml()), await ev(`${img}.getAttribute('style')`));
  t.check('the field shows it', (await ev(`${field('objectPosition')}.value`)) === '50% 0%');
  await E.panelSet('[data-tool-field="objectPosition"]', '');
  await t.waitFor(`!${img}.style.objectPosition`);
  t.check('Middle removes it', true);
  await E.panelSet('[data-tool-field="objectFit"]', 'fill');
  await t.waitFor(`!${field('objectPosition')}`);
  t.check('Stretch: no Focus (nothing to keep in view)', true);

  // ---------- 5. image Zoom (same image; Focus set again) ----------
  await E.panelSet('[data-tool-field="objectFit"]', 'cover');
  await t.waitFor(`!!${field('objectPosition')}`);
  const view = () => ev(`${img}.style.getPropertyValue('object-view-box')`);
  const size = () => ev(`(() => { const r = ${img}.getBoundingClientRect(); return Math.round(r.width) + 'x' + Math.round(r.height); })()`);
  const before = await size();
  t.check('an image has a Zoom field', await ev(`!!${field('imageZoom')}`));
  await E.panelSet('[data-tool-field="imageZoom"]', '200');
  await t.waitFor(`${img}.style.getPropertyValue('object-view-box') !== ''`);
  t.check('Zoom 200%: the middle half, object-view-box', (await view()) === 'inset(25%)' && /object-view-box: inset\(25%\)/.test(await E.modelHtml()), await view());
  t.check('the image keeps its size on the slide', (await size()) === before, before + ' -> ' + await size());
  t.check('Chrome draws it (computed)', /inset/.test(await ev(`getComputedStyle(${img}).objectViewBox`)), await ev(`getComputedStyle(${img}).objectViewBox`));
  t.check('the field reads it back', (await ev(`${field('imageZoom')}.value`)) === '200');
  await E.panelSet('[data-tool-field="objectPosition"]', '50% 0%');
  await t.waitFor(`${img}.style.getPropertyValue('object-view-box') === 'inset(0% 25% 50%)'`, { label: 'focus top moves zoomed part' });
  t.check('Focus Top moves the zoomed part to the top', true);
  await E.panelSet('[data-tool-field="imageZoom"]', '400');
  await t.waitFor(`${img}.style.getPropertyValue('object-view-box') === 'inset(0% 37.5% 75%)'`, { label: 'zoom 400 keeps focus' });
  t.check('Zoom 400% keeps the focus', true);
  await E.panelSet('[data-tool-field="objectFit"]', 'fill');
  await t.waitFor(`${img}.style.objectFit === 'fill'`);
  t.check('Stretch with zoom: Focus stays offered', await ev(`!!${field('objectPosition')}`));
  await E.panelSet('[data-tool-field="objectFit"]', '');
  await t.waitFor(`${img}.style.objectFit === ''`);
  await E.undo();
  await t.waitFor(`${img}.style.objectFit === 'fill'`);
  t.check('Undo is one step per change', true);
  await E.tab('element');
  await E.panelSet('[data-tool-field="imageZoom"]', '');
  await t.waitFor(`!${img}.style.getPropertyValue('object-view-box')`);
  t.check('Whole image removes it (Focus kept)', /50% 0%/.test(await ev(`${img}.style.objectPosition`)));
  await ev(`${img}.style.setProperty('object-view-box', 'inset(10% 20%)')`);
  await E.tab('slide'); await E.tab('element');
  await t.waitFor(`${field('imageZoom')}?.value === 'custom'`, { label: 'custom crop shown' });
  t.check('a hand-written crop shows as written', true);
  await E.panelSet('[data-tool-field="objectPosition"]', '0% 0%');
  await t.waitFor(`${img}.style.objectPosition === '0% 0%'`);
  await E.panelSet('[data-tool-field="objectFit"]', 'contain');
  await t.waitFor(`${img}.style.objectFit === 'contain'`);
  t.check('Focus and Fit leave a hand-written crop alone', (await view()) === 'inset(10% 20%)', await view());

  // ---------- 6. logo settings ----------
  await E.blur();
  await t.click('.editor-stage > .logo img');
  const logo = `document.querySelector('.editor-stage > .logo')`;
  const logoStyle = prop => ev(`getComputedStyle(${logo}).${prop}`);
  const scaleVar = `${logo}.style.getPropertyValue('--logo-scale').trim()`;
  await t.waitFor(`document.querySelector('.editor-tabs .is-selected')?.dataset.tab === 'deck' && !!document.querySelector('.editor-panel-body .editor-logo-heading')`, { label: 'logo group opens' });
  t.check('a click on the logo opens the Presentation tab at the Logo group', true);
  t.check('nothing is selected after it', await ev(gone('.editor-stage .is-editor-selected')));
  await E.panelSet('[data-logo-field="corner"]', 'bottom-left');
  await t.waitFor(`${logo}.getAttribute('data-corner') === 'bottom-left' && getComputedStyle(${logo}).left === '56px' && getComputedStyle(${logo}).bottom === '34px'`, { label: 'corner bottom left' });
  t.check('Corner bottom left: data-corner, left/bottom', true);
  await E.panelSet('[data-logo-field="size"]', '60');
  await t.waitFor(`${scaleVar} === '0.6' && /^matrix\\(0\\.6,/.test(getComputedStyle(${logo}).transform)`, { label: 'size 60' });
  t.check('Size 60: --logo-scale .6', true);
  await E.panelSet('[data-logo-field="size"]', '37');
  await t.waitFor(`!${logo}.hasAttribute('style')`);
  t.check('Size 37 (normal): no style left', true);
  await E.panelSet('[data-logo-field="size"]', '500');
  await t.waitFor(`${scaleVar} === '1'`);
  t.check('Size is kept within 10-100', true);
  await E.panelSet('[data-logo-field="size"]', '0');
  await t.waitFor(`${scaleVar} === '0.1'`);
  t.check('Size 0 becomes the smallest (10)', true);
  await E.panelSet('[data-logo-field="size"]', '37');
  await t.waitFor(`!${logo}.hasAttribute('style')`);
  await E.goSlide('title');
  await t.waitFor(`(() => { const s = document.querySelector('.editor-stage').getBoundingClientRect(), r = ${logo}.getBoundingClientRect(), k = s.width / 1600; return Math.abs((r.right - s.left) / k - 1450) <= 2 && Math.abs((r.top - s.top) / k - 150) <= 2; })()`, { label: 'large logo place' });
  t.check('first slide: large, at the same place as from the top right (right 1450, top 150)', true);
  await E.tab('deck');
  await ev(`document.querySelector('.editor-panel-body [data-logo-field="large"]').click()`);
  await t.waitFor(`${logo}.getAttribute('data-large') === 'off' && /^matrix\\(0\\.37,/.test(getComputedStyle(${logo}).transform)`, { label: 'large off' });
  t.check('Large off: small on the first slide too', true);
  await ev(`document.querySelector('.editor-panel-body [data-logo-field="show"]').click()`);
  await t.waitFor(`${logo}.hasAttribute('hidden') && getComputedStyle(${logo}).display === 'none'`);
  t.check('Show off: hidden, not drawn', true);
  await E.undo();
  await t.waitFor(`!${logo}.hasAttribute('hidden')`);
  t.check('Undo shows it again', true);
  await E.goSlide('numbers');
  await E.tab('slide');
  await ev(`document.querySelector('.editor-panel-body [data-slide-field="hideLogo"]').click()`);
  await t.waitFor(`getComputedStyle(${logo}).opacity === '0'`, { label: 'logo hidden on slide' });
  t.check('No logo on this slide: data-hide-logo, invisible, takes no clicks', /data-hide-logo/.test(await E.modelHtml()) && (await logoStyle('pointerEvents')) === 'none');
  await E.goSlide('title');
  await t.waitFor(`getComputedStyle(${logo}).opacity === '1'`, { label: 'logo back on other slide' });
  t.check('other slides keep it', true);
  await E.blur();
  await pressEsc();
  t.check('Esc with nothing to leave asks once more (v172)', await t.eval(`/Esc again/.test(document.querySelector('.toast')?.textContent || '') && !!document.querySelector('.editor-stage')?.offsetParent`));
  await pressEsc();   // (the second Esc closes it)
  await t.waitFor(`!document.querySelector('.editor-stage')?.offsetParent`, { label: 'editor closed' });
  await ev(`(() => { document.querySelector('#stage > .logo').setAttribute('data-corner', 'top-left'); document.querySelector('#stage > .scene.is-active').setAttribute('data-hide-logo', ''); })()`);
  await t.waitFor(`getComputedStyle(document.querySelector('#stage > .logo')).left === '56px' && getComputedStyle(document.querySelector('#stage > .logo')).opacity === '0'`, { label: 'live stage logo' });
  t.check('presenting: corner and hidden-on-slide work on the stage', true);
}
